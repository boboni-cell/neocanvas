不因节点多就自动分组；不把生成顺序当语义；不创建嵌套组；不让节点属两个组；不发明坐标/尺寸/颜色/frameId/任意分组字段；不承诺做不到的精细成员迁移；不在未获用户明确删除意图时删除旧组/节点/连线；不把普通整理说成创作阶段推进。
