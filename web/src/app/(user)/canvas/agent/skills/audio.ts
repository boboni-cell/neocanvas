- 朗读内容错误→检查prompt是否逐字正确，不用instructions补正文。
- 多角色混在一起→拆为每个角色一个音频节点。
- 模型/接口不支持期望控制→如实说明限制，保留声音设计文本。
- 不自动无限重试；保留失败节点供用户查看。

