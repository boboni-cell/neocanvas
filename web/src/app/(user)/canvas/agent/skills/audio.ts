每个说话角色一个可复用音色样本；有旁白/VO时一个独立narrator音色样本；不默认把剧本每句对白都生成独立音频；只有用户需要独立后期资产/精确朗读/下载复用时才生成最终对白/旁白。角色基础音色之间可以并行；最终朗读依赖已确认文本和声音选择时必须等待确认。

